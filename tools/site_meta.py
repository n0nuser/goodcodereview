JSON_CT = "application/json; charset=utf-8"


def page_slugs(b: BuildInput) -> list[str]:
    """Every page in the sitemap, as a slug."""
    return ["index", "concerns", *LEVELS, *[f"pack-{pk}" for pk in b.packs], "glossary", "drafts", "about", "privacy", "audit"]


def sitemap(slugs: Sequence[str], date: str) -> str:
    return ('<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
            + "".join(f"<url><loc>{page_url(s)}</loc><lastmod>{date}</lastmod></url>\n" for s in slugs) + "</urlset>\n")


def robots() -> str:
    return f"User-agent: *\nAllow: /\n\nSitemap: {BASE}/sitemap.xml\n"


def headers_file(slugs: Sequence[str]) -> str:
    """Return the Cloudflare static-assets `_headers` file (https://developers.cloudflare.com/workers/static-assets/headers/)."""
    script_hash = base64.b64encode(hashlib.sha256(JS.encode()).digest()).decode()
    out = ["# Generated by tools/build.py. Format: https://developers.cloudflare.com/pages/configuration/headers/",
           "/*", '  Link: </sitemap.xml>; rel="sitemap", </llms.txt>; rel="describedby"',
           f"  Strict-Transport-Security: max-age={HSTS_MAX_AGE}",
           "  X-Content-Type-Options: nosniff",
           "  Referrer-Policy: strict-origin-when-cross-origin",
           # The one inline script is a build-time constant, so its hash is allowed and nothing else may run. Inline styles stay unrestricted.
           f"  Content-Security-Policy: frame-ancestors 'none'; script-src 'sha256-{script_hash}'; object-src 'none'; base-uri 'none'"]
    for s in slugs:
        out += ["/" if s == "index" else f"/{s}", f'  Link: </{s}.md>; rel="alternate"; type="text/markdown"']
    out += ["/*.md", "  Content-Type: text/markdown; charset=utf-8", "/*.txt", "  Content-Type: text/plain; charset=utf-8",
            "/sitemap.xml", "  Content-Type: application/xml; charset=utf-8",
            "/.well-known/agent-skills/index.json", f"  Content-Type: {JSON_CT}"]
    return "\n".join(out) + "\n"


def security_txt(date: str) -> str:
    """RFC 9116. Expires is SECURITY_TXT_DAYS after the build date, so each rebuild renews it."""
    expires = (datetime.date.fromisoformat(date) + datetime.timedelta(days=SECURITY_TXT_DAYS)).isoformat()
    return ("Contact: mailto:contact@pablogonzalez.me\n"
            f"Contact: {REPO}/security/advisories/new\n"
            f"Expires: {expires}T00:00:00Z\n"
            "Preferred-Languages: en, es\n"
            f"Canonical: {BASE}/.well-known/security.txt\n"
            f"Policy: {REPO}/blob/main/SECURITY.md\n")


def _card_model(card: Card) -> schema.Card:
    fm = card.fm
    found = orgs.split(fm["borrowed_from"])
    draft_lack = lacks(card)
    return schema.Card(
        id=fm["id"], level=fm["level"], status=fm["status"], severity=fm["severity"], concerns=concerns(card),
        topics=topics(card), lang=fm["lang"], applies_when=fm["applies_when"], context=fm.get("context", []),
        tool_gate=None if fm["tool_gate"] == "none" else fm["tool_gate"], note=fm.get("note"),
        lacks=schema.Lacks(LacksReason(draft_lack.reason), draft_lack.note) if draft_lack else None,
        rule=rule(card.body), why=section(card.body, "Why"), counterpoint=section(card.body, "Counterpoint"),
        fail=schema.example(card.body, "FAIL"), pass_=schema.example(card.body, "PASS"), sources=fm["borrowed_from"],
        orgs=[schema.Org(g.id, orgs.ORGS[g.id], g.urls) for g in found.organisations],
        people=[schema.Org(g.id, orgs.ORGS[g.id], g.urls) for g in found.people],
        url=f"{page_url(page_name(card))}#{fm['id']}", markdown_url=markdown_url(card))


def corpus(kind: schema.Kind, cards: Sequence[Card], b: BuildInput) -> schema.Corpus:
    """The cards.json model: kind "stable" for the vetted cards, "drafts" for every other card."""
    levels = [schema.LevelInfo(
        id=lv, name=NAME[lv], input=INPUT[lv], description=LEVEL_DESC[lv], stable_count=b.counts[lv].stable, draft_count=b.counts[lv].draft,
        gives_verdict=bool(b.counts[lv].stable), url=page_url(lv), markdown_url=f"{BASE}/{lv}.md") for lv in LEVELS]
    return schema.Corpus(schema.SCHEMA_VERSION, kind, SITE_NAME, f"{BASE}/", LICENCE_URL, b.date, list(CONCERNS), levels,
                         [_card_model(c) for c in cards])


def cards_files(b: BuildInput) -> dict[str, str]:
    """cards.schema.json, cards.json, and cards-drafts.json. Raises BuildError when a file breaks its schema or passes CARDS_JSON_BUDGET."""
    sch = schema.json_schema(BASE)
    files = {"cards.schema.json": json.dumps(sch, indent=2) + "\n"}
    for name, kind, cards in (("cards.json", schema.Kind.STABLE, b.stable), ("cards-drafts.json", schema.Kind.DRAFTS, b.draft)):
        data = schema.to_dict(corpus(kind, cards, b))
        if problems := schema.check(sch, data):
            raise BuildError(f"{name} does not match cards.schema.json:\n" + "\n".join(problems[:10]))
        text = json.dumps(data, indent=1, ensure_ascii=False) + "\n"
        size = len(text.encode())
        if size > CARDS_JSON_BUDGET:
            raise BuildError(f"{name} is {size} bytes, budget {CARDS_JSON_BUDGET}: it is one unpaginated file; see docs/cards-json.md before raising it")
        files[name] = text
    return files


def skill_discovery(skill_files: dict[str, str]) -> dict[str, str]:
    """Serve the skill and its references under .well-known, and list it with the sha256 digest of the served SKILL.md."""
    root = f".well-known/agent-skills/{SKILL_NAME}"
    files = {f"{root}/{rel}": text for rel, text in skill_files.items()}
    digest = hashlib.sha256(skill_files["SKILL.md"].encode()).hexdigest()
    index = {"$schema": "https://schemas.agentskills.io/discovery/0.2.0/schema.json",
             "skills": [{"name": SKILL_NAME, "type": "skill-md", "description": SKILL_DESC,
                         "url": f"{BASE}/{root}/SKILL.md", "digest": f"sha256:{digest}"}]}
    files[".well-known/agent-skills/index.json"] = json.dumps(index, indent=2) + "\n"
    return files

